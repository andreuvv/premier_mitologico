GRANT EXECUTE ON FUNCTION public.update_active_tournament(text, text, integer, date, date, text, bigint, bigint, text, bigint[], text, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.set_active_pairing_mode(p_mode text)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF p_mode NOT IN ('fixed', 'progressive') THEN
    RAISE EXCEPTION 'invalid pairing mode';
  END IF;

  UPDATE public.tournaments
  SET pairing_mode = p_mode
  WHERE is_active;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'no active tournament';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.append_active_round(p_round jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_tournament_id bigint;
  v_format text;
  v_round_id bigint;
  v_round_format text;
  v_match jsonb;
  v_player1 bigint;
  v_player2 bigint;
  v_expected integer;
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT id, format INTO v_tournament_id, v_format
  FROM public.tournaments
  WHERE is_active
  LIMIT 1;

  IF v_tournament_id IS NULL THEN
    RAISE EXCEPTION 'no active tournament';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.active_tournaments_matches m
    JOIN public.active_tournaments_rounds r ON r.id = m.round_id
    WHERE r.tournament_id = v_tournament_id
      AND m.player2_id IS NOT NULL
      AND NOT m.completed
  ) THEN
    RAISE EXCEPTION 'previous round is not complete';
  END IF;

  SELECT COALESCE(MAX(round_number), 0) + 1 INTO v_expected
  FROM public.active_tournaments_rounds
  WHERE tournament_id = v_tournament_id;

  IF (p_round->>'round_number')::integer IS DISTINCT FROM v_expected THEN
    RAISE EXCEPTION 'round number is out of sequence';
  END IF;

  v_round_format := p_round->>'format';
  IF v_round_format NOT IN ('PB', 'FX') THEN
    RAISE EXCEPTION 'invalid round format';
  END IF;
  IF v_format = 'PB' AND v_round_format <> 'PB' THEN
    RAISE EXCEPTION 'round format does not match tournament';
  END IF;
  IF v_format = 'FX' AND v_round_format <> 'FX' THEN
    RAISE EXCEPTION 'round format does not match tournament';
  END IF;

  IF jsonb_array_length(COALESCE(p_round->'matches', '[]'::jsonb)) < 1 THEN
    RAISE EXCEPTION 'round has no matches';
  END IF;

  INSERT INTO public.active_tournaments_rounds (
    tournament_id, round_number, format, subformat_id, is_extra_round
  ) VALUES (
    v_tournament_id,
    v_expected,
    v_round_format,
    NULLIF(p_round->>'subformat_id', '')::bigint,
    COALESCE((p_round->>'is_extra_round')::boolean, false)
  )
  RETURNING id INTO v_round_id;

  FOR v_match IN SELECT value FROM jsonb_array_elements(p_round->'matches') LOOP
    v_player1 := (v_match->>'player1_id')::bigint;
    v_player2 := NULLIF(v_match->>'player2_id', '')::bigint;

    IF NOT EXISTS (
      SELECT 1 FROM public.active_tournament_player
      WHERE tournament_id = v_tournament_id AND player_id = v_player1
    ) THEN
      RAISE EXCEPTION 'player % is not in the active roster', v_player1;
    END IF;

    IF v_player2 IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM public.active_tournament_player
      WHERE tournament_id = v_tournament_id AND player_id = v_player2
    ) THEN
      RAISE EXCEPTION 'player % is not in the active roster', v_player2;
    END IF;

    INSERT INTO public.active_tournaments_matches (
      tournament_id, round_id, player1_id, player2_id
    ) VALUES (
      v_tournament_id, v_round_id, v_player1, v_player2
    );
  END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION public.set_active_pairing_mode(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.append_active_round(jsonb) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.set_active_pairing_mode(text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.append_active_round(jsonb) TO authenticated;

CREATE OR REPLACE FUNCTION public.sync_tournament_sequences()
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF coalesce(auth.role(), '') <> 'service_role' AND NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;
  PERFORM setval(pg_get_serial_sequence('public.tournaments', 'id'), GREATEST(COALESCE((SELECT MAX(id) FROM public.tournaments), 1), 1));
  PERFORM setval(pg_get_serial_sequence('public.archived_tournaments_rounds', 'id'), GREATEST(COALESCE((SELECT MAX(id) FROM public.archived_tournaments_rounds), 1), 1));
END;
$$;

