CREATE OR REPLACE FUNCTION public.create_tournament(
  p_name text,
  p_month text,
  p_year integer,
  p_start_date date,
  p_end_date date,
  p_format text,
  p_subformat1_id bigint,
  p_subformat2_id bigint,
  p_tournament_type text,
  p_player_ids bigint[],
  p_location_name text,
  p_location_address text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_id bigint;
  v_player_id bigint;
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  IF EXISTS (SELECT 1 FROM public.tournaments WHERE is_active) THEN
    RAISE EXCEPTION 'already exists an active tournament';
  END IF;

  IF p_format NOT IN ('PB', 'FX', 'PBFX') THEN
    RAISE EXCEPTION 'invalid format';
  END IF;

  IF p_subformat1_id IS NULL OR p_subformat2_id IS NULL THEN
    RAISE EXCEPTION 'subformat required';
  END IF;

  IF p_player_ids IS NULL OR cardinality(p_player_ids) < 2 THEN
    RAISE EXCEPTION 'at least two players are required';
  END IF;

  p_location_name := nullif(btrim(p_location_name), '');
  p_location_address := nullif(btrim(p_location_address), '');

  INSERT INTO public.tournaments (
    name, month, year, start_date, end_date, is_active, format,
    subformat1_id, subformat2_id, tournament_type, location_name, location_address
  ) VALUES (
    p_name, p_month, p_year, p_start_date, p_end_date, true, p_format,
    p_subformat1_id, p_subformat2_id, p_tournament_type, p_location_name, p_location_address
  )
  RETURNING id INTO v_id;

  FOREACH v_player_id IN ARRAY p_player_ids LOOP
    INSERT INTO public.active_tournament_player (tournament_id, player_id, confirmed)
    VALUES (v_id, v_player_id, true);
  END LOOP;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.replace_active_fixture(p_rounds jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_tournament_id bigint;
  v_format text;
  v_round jsonb;
  v_match jsonb;
  v_round_id bigint;
  v_round_format text;
  v_player1 bigint;
  v_player2 bigint;
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT id, format INTO v_tournament_id, v_format
  FROM public.tournaments
  WHERE is_active
  LIMIT 1;

  IF v_tournament_id IS NULL THEN
    RAISE EXCEPTION 'no active tournament';
  END IF;

  DELETE FROM public.active_tournaments_rounds WHERE tournament_id = v_tournament_id;

  FOR v_round IN SELECT value FROM jsonb_array_elements(p_rounds) LOOP
    v_round_format := v_round->>'format';
    IF v_round_format NOT IN ('PB', 'FX') THEN
      RAISE EXCEPTION 'invalid round format';
    END IF;
    IF v_format = 'PB' AND v_round_format <> 'PB' THEN
      RAISE EXCEPTION 'round format does not match tournament';
    END IF;
    IF v_format = 'FX' AND v_round_format <> 'FX' THEN
      RAISE EXCEPTION 'round format does not match tournament';
    END IF;

    INSERT INTO public.active_tournaments_rounds (
      tournament_id, round_number, format, subformat_id, is_extra_round
    ) VALUES (
      v_tournament_id,
      (v_round->>'round_number')::integer,
      v_round_format,
      NULLIF(v_round->>'subformat_id', '')::bigint,
      COALESCE((v_round->>'is_extra_round')::boolean, false)
    )
    RETURNING id INTO v_round_id;

    FOR v_match IN SELECT value FROM jsonb_array_elements(COALESCE(v_round->'matches', '[]'::jsonb)) LOOP
      v_player1 := (v_match->>'player1_id')::bigint;
      v_player2 := NULLIF(v_match->>'player2_id', '')::bigint;

      IF NOT EXISTS (
        SELECT 1 FROM public.active_tournament_player
        WHERE tournament_id = v_tournament_id AND player_id = v_player1
      ) THEN
        RAISE EXCEPTION 'player % is not in the active roster', v_player1;
      END IF;

      IF v_player2 IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.active_tournament_player
        WHERE tournament_id = v_tournament_id AND player_id = v_player2
      ) THEN
        RAISE EXCEPTION 'player % is not in the active roster', v_player2;
      END IF;

      INSERT INTO public.active_tournaments_matches (
        tournament_id, round_id, player1_id, player2_id
      ) VALUES (
        v_tournament_id, v_round_id, v_player1, v_player2
      );
    END LOOP;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_match_score(
  p_match_id bigint,
  p_score1 integer,
  p_score2 integer
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_tournament_id bigint;
  v_player1 bigint;
  v_player2 bigint;
  v_games integer;
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT tournament_id, player1_id, player2_id
  INTO v_tournament_id, v_player1, v_player2
  FROM public.active_tournaments_matches
  WHERE id = p_match_id;

  IF v_tournament_id IS NULL THEN
    RAISE EXCEPTION 'match not found';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.tournaments WHERE id = v_tournament_id AND is_active) THEN
    RAISE EXCEPTION 'match is not in the active tournament';
  END IF;

  UPDATE public.active_tournaments_matches
  SET score1 = p_score1,
      score2 = p_score2,
      completed = true
  WHERE id = p_match_id;

  v_games := COALESCE(p_score1, 0) + COALESCE(p_score2, 0);

  INSERT INTO public.active_tournament_player_match_stats (
    tournament_id, player_id, match_id, games_played, games_won
  ) VALUES (
    v_tournament_id, v_player1, p_match_id, v_games, COALESCE(p_score1, 0)
  )
  ON CONFLICT (player_id, match_id) DO UPDATE
  SET games_played = EXCLUDED.games_played,
      games_won = EXCLUDED.games_won;

  IF v_player2 IS NOT NULL THEN
    INSERT INTO public.active_tournament_player_match_stats (
      tournament_id, player_id, match_id, games_played, games_won
    ) VALUES (
      v_tournament_id, v_player2, p_match_id, v_games, COALESCE(p_score2, 0)
    )
    ON CONFLICT (player_id, match_id) DO UPDATE
    SET games_played = EXCLUDED.games_played,
        games_won = EXCLUDED.games_won;
  END IF;
END;
$$;

