CREATE OR REPLACE FUNCTION public.update_active_tournament(
  p_name text,
  p_month text,
  p_year integer,
  p_start_date date,
  p_end_date date,
  p_format text,
  p_subformat1_id bigint,
  p_subformat2_id bigint,
  p_tournament_type text,
  p_player_ids bigint[],
  p_location_name text,
  p_location_address text
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_id bigint;
  v_format text;
  v_old_sub1 bigint;
  v_old_sub2 bigint;
  v_player_id bigint;
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT id, format, subformat1_id, subformat2_id
  INTO v_id, v_format, v_old_sub1, v_old_sub2
  FROM public.tournaments
  WHERE is_active
  LIMIT 1;

  IF v_id IS NULL THEN
    RAISE EXCEPTION 'no active tournament';
  END IF;

  IF p_format NOT IN ('PB', 'FX', 'PBFX') THEN
    RAISE EXCEPTION 'invalid format';
  END IF;

  IF p_subformat1_id IS NULL OR p_subformat2_id IS NULL THEN
    RAISE EXCEPTION 'subformat required';
  END IF;

  IF p_player_ids IS NULL OR cardinality(p_player_ids) < 2 THEN
    RAISE EXCEPTION 'at least two players are required';
  END IF;

  p_location_name := nullif(btrim(p_location_name), '');
  p_location_address := nullif(btrim(p_location_address), '');

  IF v_format IS DISTINCT FROM p_format AND EXISTS (
    SELECT 1 FROM public.active_tournaments_rounds WHERE tournament_id = v_id
  ) THEN
    RAISE EXCEPTION 'borra el fixture antes de cambiar entre PB, FX y PBFX';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.active_tournament_player AS roster
    WHERE roster.tournament_id = v_id
      AND NOT (roster.player_id = ANY(p_player_ids))
      AND EXISTS (
        SELECT 1
        FROM public.active_tournaments_matches AS matches
        WHERE matches.tournament_id = v_id
          AND (matches.player1_id = roster.player_id OR matches.player2_id = roster.player_id)
      )
  ) THEN
    RAISE EXCEPTION 'borra el fixture antes de quitar un jugador que ya tiene partidas';
  END IF;

  UPDATE public.tournaments
  SET name = p_name,
      month = p_month,
      year = p_year,
      start_date = p_start_date,
      end_date = p_end_date,
      format = p_format,
      subformat1_id = p_subformat1_id,
      subformat2_id = p_subformat2_id,
      tournament_type = p_tournament_type,
      location_name = p_location_name,
      location_address = p_location_address
  WHERE id = v_id;

  UPDATE public.active_tournaments_rounds
  SET subformat_id = CASE
    WHEN p_format = 'PBFX' AND format = 'FX' THEN p_subformat2_id
    WHEN p_format = 'PBFX' AND format = 'PB' THEN p_subformat1_id
    WHEN subformat_id IS NOT DISTINCT FROM v_old_sub2 THEN p_subformat2_id
    WHEN subformat_id IS NOT DISTINCT FROM v_old_sub1 THEN p_subformat1_id
    ELSE subformat_id
  END
  WHERE tournament_id = v_id;

  DELETE FROM public.active_tournament_player
  WHERE tournament_id = v_id
    AND NOT (player_id = ANY(p_player_ids));

  FOREACH v_player_id IN ARRAY p_player_ids LOOP
    INSERT INTO public.active_tournament_player (tournament_id, player_id, confirmed)
    VALUES (v_id, v_player_id, true)
    ON CONFLICT (tournament_id, player_id) DO UPDATE SET confirmed = true;
  END LOOP;
END;
$$;

