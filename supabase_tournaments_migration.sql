CREATE TABLE public.tournaments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  month text NOT NULL,
  year integer NOT NULL,
  start_date date,
  end_date date,
  is_active boolean NOT NULL DEFAULT false,
  format text NOT NULL CHECK (format IN ('PB', 'FX', 'PBFX')),
  subformat1_id bigint REFERENCES public.game_subformats (subformat_id),
  subformat2_id bigint REFERENCES public.game_subformats (subformat_id),
  tournament_type text NOT NULL CHECK (tournament_type IN ('premier_mitoxico', 'special_event')),
  location_name text,
  location_address text,
  pairing_mode text NOT NULL DEFAULT 'fixed' CHECK (pairing_mode IN ('fixed', 'progressive')),
  created_at timestamptz NOT NULL DEFAULT now(),
  archived_at timestamptz
);

CREATE UNIQUE INDEX tournaments_one_active_idx
  ON public.tournaments (is_active)
  WHERE is_active;

CREATE INDEX tournaments_year_month_idx ON public.tournaments (year DESC, month);

