CREATE OR REPLACE VIEW public.active_tournament_standings
WITH (security_invoker = true) AS
SELECT
  atp.tournament_id,
  atp.player_id,
  pp.display_name,
  COUNT(m.id) FILTER (WHERE m.completed) AS matches_played,
  COUNT(m.id) FILTER (
    WHERE m.completed AND (
      (m.player1_id = atp.player_id AND m.score1 > m.score2)
      OR (m.player2_id = atp.player_id AND m.score2 > m.score1)
    )
  ) AS wins,
  COUNT(m.id) FILTER (
    WHERE m.completed
      AND m.player2_id IS NOT NULL
      AND m.score1 = m.score2
  ) AS ties,
  COUNT(m.id) FILTER (
    WHERE m.completed AND (
      (m.player1_id = atp.player_id AND m.score1 < m.score2)
      OR (m.player2_id = atp.player_id AND m.score2 < m.score1)
    )
  ) AS losses,
  COALESCE(SUM(
    CASE
      WHEN NOT m.completed THEN 0
      WHEN (m.player1_id = atp.player_id AND m.score1 > m.score2)
        OR (m.player2_id = atp.player_id AND m.score2 > m.score1) THEN 3
      WHEN m.player2_id IS NOT NULL AND m.score1 = m.score2 THEN 1
      ELSE 0
    END
  ), 0) AS points,
  COALESCE(SUM(st.games_won) FILTER (WHERE m.completed), 0) AS total_points_scored,
  COALESCE(SUM(st.games_played) FILTER (WHERE m.completed), 0) AS total_matches
FROM public.active_tournament_player atp
JOIN public.tournaments t ON t.id = atp.tournament_id AND t.is_active
JOIN public.premier_players pp ON pp.premier_id = atp.player_id
LEFT JOIN public.active_tournaments_matches m
  ON m.tournament_id = atp.tournament_id
 AND (m.player1_id = atp.player_id OR m.player2_id = atp.player_id)
LEFT JOIN public.active_tournament_player_match_stats st
  ON st.match_id = m.id
 AND st.player_id = atp.player_id
WHERE atp.confirmed
GROUP BY atp.tournament_id, atp.player_id, pp.display_name;

