CREATE OR REPLACE FUNCTION public.archive_active_tournament(p_standings jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_tournament_id bigint;
  v_round record;
  v_new_round_id bigint;
BEGIN
  IF NOT public.is_tournament_admin() THEN
    RAISE EXCEPTION 'not authorized';
  END IF;

  SELECT id INTO v_tournament_id FROM public.tournaments WHERE is_active LIMIT 1;
  IF v_tournament_id IS NULL THEN
    RAISE EXCEPTION 'no active tournament';
  END IF;

  FOR v_round IN
    SELECT * FROM public.active_tournaments_rounds
    WHERE tournament_id = v_tournament_id
    ORDER BY round_number
  LOOP
    INSERT INTO public.archived_tournaments_rounds (
      tournament_id, round_number, format, subformat_id, is_extra_round
    ) VALUES (
      v_tournament_id, v_round.round_number, v_round.format, v_round.subformat_id, v_round.is_extra_round
    )
    RETURNING id INTO v_new_round_id;

    INSERT INTO public.archived_tournaments_matches (
      tournament_id, round_id, player1_id, player2_id, score1, score2, completed
    )
    SELECT v_tournament_id, v_new_round_id, player1_id, player2_id, score1, score2, completed
    FROM public.active_tournaments_matches
    WHERE round_id = v_round.id;
  END LOOP;

  INSERT INTO public.archived_tournaments_standings (
    tournament_id, player_id, matches_played, wins, ties, losses, points,
    total_points_scored, total_matches, final_position
  )
  SELECT
    v_tournament_id,
    s.player_id,
    s.matches_played,
    s.wins,
    s.ties,
    s.losses,
    s.points,
    s.total_points_scored,
    s.total_matches,
    s.final_position
  FROM jsonb_to_recordset(p_standings) AS s(
    player_id bigint,
    matches_played integer,
    wins integer,
    ties integer,
    losses integer,
    points integer,
    total_points_scored integer,
    total_matches integer,
    final_position integer
  )
  WHERE EXISTS (
    SELECT 1 FROM public.active_tournament_player p
    WHERE p.tournament_id = v_tournament_id AND p.player_id = s.player_id
  );

  UPDATE public.tournaments
  SET is_active = false, archived_at = now()
  WHERE id = v_tournament_id;

  DELETE FROM public.active_tournaments_rounds WHERE tournament_id = v_tournament_id;
  DELETE FROM public.active_tournament_player WHERE tournament_id = v_tournament_id;

  RETURN v_tournament_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.clear_active_tournament(p_clear_players boolean)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_tournament_id bigint;
BEGIN
